function _tutorialBlockHtml(b) {
    if (b.h) return `<h4 class="t-h">${b.h}</h4>`;
    if (b.p) return `<p class="t-p">${b.p}</p>`;
    if (b.ul) return `<ul class="t-ul">${b.ul.map(i => `<li>${i}</li>`).join('')}</ul>`;
    if (b.tip) return `<p class="t-tip">💡 ${b.tip}</p>`;
    return '';
}

function _appendTutorialModule(m) {
    const item = document.createElement('div');
    item.className = 'tutorial-item';
    const body = m.blocks.map(_tutorialBlockHtml).join('');
    item.innerHTML = `<div class="tutorial-header">${m.title}</div><div class="tutorial-content">${body}</div>`;
    tutorialContentArea.appendChild(item);
}

function renderTutorialContent() {
    tutorialContentArea.innerHTML = '';
    // 顺序：写在最前 → 更新日志 → 各模块使用说明
    _appendTutorialModule(usageModules[0]);
    renderUpdateLog();
    for (let i = 1; i < usageModules.length; i++) _appendTutorialModule(usageModules[i]);
}
